/// Kelas utilitas yang berisi konstanta untuk spasi dan padding yang konsisten
/// di seluruh aplikasi. Menggunakan skala berbasis 4px.
class AppSpacing {
  // Private constructor agar kelas ini tidak bisa diinstansiasi.
  AppSpacing._();

  /// Spasi sangat sangat kecil: 4.0
  static const double xxs = 4.0;

  /// Spasi sangat kecil: 8.0
  static const double xs = 8.0;

  /// Spasi kecil: 12.0
  static const double sm = 12.0;

  /// Spasi medium, sering digunakan sebagai padding default: 16.0
  static const double md = 16.0;

  /// Spasi besar: 24.0
  static const double lg = 24.0;

  /// Spasi sangat besar: 32.0
  static const double xlg = 32.0;
  static const double xxl = 35.0;

  /// Spasi sangat sangat besar: 40.0
  static const double xxlg = 40.0;
}
